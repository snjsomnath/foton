#!/usr/bin/env python3
"""Rewrite the README speed table from a benchmark-suite result.

Takes the newest full run under ``benchmarks/machines/`` (or the newest for
``--machine``) and replaces everything between the ``speed-table`` markers in
README.md with a plain-language summary: date, machine, settings and a table of
annual-run and Grasshopper round-trip times. Text outside the markers is left
alone, so comparisons and commentary stay hand-written.

    python scripts/benchmark_suite.py
    python scripts/refresh_readme_speed.py
"""

from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from compare_benchmarks import MACHINES  # noqa: E402
import json  # noqa: E402

START = "<!-- speed-table:start (generated by scripts/refresh_readme_speed.py) -->"
END = "<!-- speed-table:end -->"
REPOSITORY = "https://github.com/snjsomnath/foton/blob/main"
SCENE_NAMES = {
    "teaching_office": "Teaching office",
    "courtyard_rooms": "Courtyard with four rooms",
    "acceptance": "Acceptance model",
    "office_floors": "Four-storey office block",
}


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--machine", help="Machine ID; default is the newest result of any machine.")
    parser.add_argument("--folder", default=str(MACHINES))
    parser.add_argument("--readme", default=str(ROOT / "README.md"))
    parser.add_argument(
        "--check", action="store_true", help="Exit 1 if the README is out of date; write nothing."
    )
    return parser.parse_args(argv)


def select_result(results, machine=None):
    candidates = [
        result
        for result in results
        if machine is None or result["fingerprint"]["machine_id"] == machine
    ]
    if not candidates:
        raise SystemExit(f"no full benchmark-suite result found for {machine or 'any machine'}")
    return max(candidates, key=lambda result: result["recorded_at_utc"])


def _date(recorded):
    moment = datetime.strptime(recorded, "%Y-%m-%d %H:%M:%SZ")
    return f"{moment.day} {moment:%B %Y}"


def _machine(fingerprint):
    hardware, gpu = fingerprint["hardware"], fingerprint["gpu"]
    parts = [hardware["cpu"], hardware["memory"]]
    if gpu["name"] != hardware["cpu"]:
        parts.append(gpu["name"])
    article = "an" if fingerprint["model_name"][:1].lower() in "aeiou" else "a"
    return f"{article} {fingerprint['model_name']} ({', '.join(parts)})"


def _seconds(value):
    return f"{value:.2f} s"


def speed_block(result, path):
    fingerprint = result["fingerprint"]
    annual = result["annual"]
    settings = annual["settings"]
    backend = {"metal": "Metal", "vulkan": "Vulkan"}.get(fingerprint["backend"], fingerprint["backend"])
    commit = fingerprint["foton"].get("commit")
    version = f"Foton {fingerprint['foton']['version']}" + (f" (commit `{commit[:7]}`)" if commit else "")
    trips = {
        case["scene"]: case["median_seconds"]["round_trip_total"]
        for case in (result.get("grasshopper") or {}).get("cases", [])
    }
    summary = (
        f"Measured on {_date(result['recorded_at_utc'])} on {_machine(fingerprint)}, using "
        f"{backend} and {version} at its default `{annual['quality']}` quality "
        f"({settings['maximum_bounces']} bounces, {settings['direct_samples']:,} direct and "
        f"{settings['maximum_samples']:,} indirect samples, 146-patch sky, "
        f"{Path(annual['weather']).stem.title()} weather). An annual run starts from a model "
        "Foton has not seen before: loading it, building the GPU scene, tracing, and writing "
        "DA and UDI for all 8,760 hours. The Grasshopper round trip adds writing the HBJSON, "
        "starting Foton and reading the results back. Annual times are the median of "
        f"{annual['repeats']} runs and round trips the median of "
        f"{(result.get('grasshopper') or {}).get('repeats', 0)}."
    )
    lines = [
        START,
        summary,
        "",
        "| Model | Rooms | Sensors | Annual run | Grasshopper round trip |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for case in annual["cases"]:
        name = SCENE_NAMES.get(case["scene"], case["scene"].replace("_", " ").capitalize())
        trip = _seconds(trips[case["scene"]]) if case["scene"] in trips else "–"
        lines.append(
            f"| {name} | {case['rooms']:,} | {case['sensors']:,} | "
            f"{_seconds(case['wall_seconds']['median'])} | {trip} |"
        )
    relative = path.resolve().relative_to(ROOT).as_posix()
    lines += [
        "",
        f"Raw data: [{fingerprint['machine_id']}]({REPOSITORY}/{relative}). "
        f"Other machines: [results by machine]({REPOSITORY}/benchmarks/machines/README.md).",
        END,
    ]
    return "\n".join(lines)


def replace_block(text, block):
    if START not in text or END not in text:
        raise SystemExit(f"README has no speed-table markers; add\n{START}\n{END}\nwhere the table belongs")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return before + block + after


def main():
    args = parse_args()
    paths = sorted(Path(args.folder).glob("*/*.json"))
    loaded = [(json.loads(path.read_text(encoding="utf-8")), path) for path in paths]
    results = [entry for entry in loaded if not entry[0].get("quick")]
    result = select_result([result for result, _ in results], args.machine)
    path = next(path for candidate, path in results if candidate is result)
    readme = Path(args.readme)
    text = readme.read_text(encoding="utf-8")
    updated = replace_block(text, speed_block(result, path))
    if args.check:
        if updated != text:
            print("README speed table is out of date; run scripts/refresh_readme_speed.py")
            return 1
        return 0
    readme.write_text(updated, encoding="utf-8")
    print(f"Updated {readme} from {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
