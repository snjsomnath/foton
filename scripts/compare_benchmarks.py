#!/usr/bin/env python3
"""Tabulate benchmark-suite results from every machine.

Reads ``benchmarks/machines/*/*.json`` written by ``benchmark_suite.py`` and
prints one row per machine and Foton commit, using the newest result for each.
Quick (smoke) runs are left out. ``--write`` also saves the table to
``benchmarks/machines/README.md``.

    python scripts/compare_benchmarks.py --write
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MACHINES = ROOT / "benchmarks" / "machines"
README_HEADER = """# Benchmark results by machine

Generated by `python scripts/compare_benchmarks.py --write` from the JSON files
in this folder. Each row is the newest full run of `scripts/benchmark_suite.py`
for one machine and Foton commit. Annual times are a cold annual-daylight run at
the shipped defaults (median of five); round trip is the Grasshopper component
path from HBJSON to loaded results (median of three). Times are in seconds.

"""


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--folder", default=str(MACHINES))
    parser.add_argument("--all", action="store_true", help="Show every run, not only the newest.")
    parser.add_argument("--write", action="store_true", help="Write the table to README.md.")
    return parser.parse_args(argv)


def load_results(folder):
    results = []
    for path in sorted(Path(folder).glob("*/*.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        if result.get("quick"):
            continue
        results.append(result)
    return results


def newest_per_machine(results):
    newest = {}
    for result in results:
        fingerprint = result["fingerprint"]
        key = (fingerprint["machine_id"], fingerprint["foton"]["commit"])
        if key not in newest or result["recorded_at_utc"] > newest[key]["recorded_at_utc"]:
            newest[key] = result
    return list(newest.values())


def comparison_markdown(results):
    annual_scenes, trip_scenes = [], []
    for result in results:
        for case in result["annual"]["cases"]:
            if case["scene"] not in annual_scenes:
                annual_scenes.append(case["scene"])
        for case in (result.get("grasshopper") or {}).get("cases", []):
            if case["scene"] not in trip_scenes:
                trip_scenes.append(case["scene"])
    header = (
        ["Machine", "GPU", "Backend", "OS", "Foton", "Date"]
        + [f"Annual: {scene}" for scene in annual_scenes]
        + [f"Round trip: {scene}" for scene in trip_scenes]
    )
    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] * 6 + ["---:"] * (len(header) - 6)) + " |",
    ]
    ordered = sorted(
        results,
        key=lambda r: (r["fingerprint"]["machine_id"], r["recorded_at_utc"]),
    )
    for result in ordered:
        fingerprint = result["fingerprint"]
        hardware, gpu, foton = fingerprint["hardware"], fingerprint["gpu"], fingerprint["foton"]
        annual = {case["scene"]: case["wall_seconds"]["median"] for case in result["annual"]["cases"]}
        trip = {
            case["scene"]: case["median_seconds"]["round_trip_total"]
            for case in (result.get("grasshopper") or {}).get("cases", [])
        }
        cores = f", {gpu['cores']} cores" if gpu.get("cores") else ""
        commit = (foton.get("commit") or "unknown")[:7] + (" (dirty)" if foton.get("dirty") else "")
        cells = [
            f"{fingerprint.get('model_name', hardware['model'])}, {hardware['cpu']}, {hardware['memory']}",
            f"{gpu['name']}{cores}" + (f", driver {gpu['driver']}" if gpu.get("driver") else ""),
            fingerprint["backend"],
            fingerprint["os"],
            f"{foton['version']} `{commit}`",
            result["recorded_at_utc"][:10],
        ]
        cells += [f"{annual[scene]:.2f}" if scene in annual else "" for scene in annual_scenes]
        cells += [f"{trip[scene]:.2f}" if scene in trip else "" for scene in trip_scenes]
        lines.append("| " + " | ".join(cells).replace("\n", " ") + " |")
    return "\n".join(lines) + "\n"


def main():
    args = parse_args()
    results = load_results(args.folder)
    if not results:
        print(f"No full benchmark-suite results under {args.folder}")
        return 1
    if not args.all:
        results = newest_per_machine(results)
    table = comparison_markdown(results)
    print(table)
    if args.write:
        (Path(args.folder) / "README.md").write_text(README_HEADER + table, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
